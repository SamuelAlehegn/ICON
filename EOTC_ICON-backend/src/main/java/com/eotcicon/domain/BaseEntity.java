package com.eotcicon.domain;

import java.time.Instant;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.MappedSuperclass;
import jakarta.persistence.PrePersist;
import jakarta.persistence.PreUpdate;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.Setter;

/**
 * Common mapping of every table in the schema: the surrogate {@code UUID}
 * primary key and the {@code created_at} / {@code updated_at} audit columns.
 *
 * <p>
 * The key is generated by the application layer ({@link GenerationType#UUID}),
 * so the DDL needs no database-side default and stays identical on H2 and
 * PostgreSQL. The timestamps are maintained by the JPA lifecycle callbacks
 * instead of a database trigger, because triggers are not portable across the
 * two engines.
 */
@Getter
@Setter
@MappedSuperclass
public abstract class BaseEntity {

	@Id
	@GeneratedValue(strategy = GenerationType.UUID)
	@Column(name = "id", nullable = false, updatable = false)
	@Setter(AccessLevel.NONE)
	private UUID id;

	@Column(name = "created_at", nullable = false, updatable = false)
	@Setter(AccessLevel.NONE)
	private Instant createdAt;

	@Column(name = "updated_at", nullable = false)
	@Setter(AccessLevel.NONE)
	private Instant updatedAt;

	/**
	 * Stamps the audit columns on insert. Both columns have a database default
	 * as well, but the application is the single writer so that the values do
	 * not depend on the engine's clock handling.
	 */
	@PrePersist
	protected void onPersist() {
		Instant now = Instant.now();
		if (createdAt == null) {
			createdAt = now;
		}
		updatedAt = now;
	}

	/**
	 * Refreshes {@code updated_at} on every update.
	 */
	@PreUpdate
	protected void onUpdate() {
		updatedAt = Instant.now();
	}

	/**
	 * Identity comparison by primary key. Transient instances (no key yet) are
	 * only equal to themselves, and the hash code is derived from the type
	 * instead of the key so that it does not change once the key is assigned.
	 */
	@Override
	public boolean equals(Object other) {
		if (this == other) {
			return true;
		}
		if (!(other instanceof BaseEntity that)) {
			return false;
		}
		UUID thisId = getId();
		return thisId != null && thisId.equals(that.getId());
	}

	@Override
	public int hashCode() {
		return getClass().hashCode();
	}

}
