-- =============================================================================
-- V2__create_core_schema.sql — Core domain schema (archive, users, moderation)
-- Migration set: classpath:db/h2 (profile `local`, the default profile)
-- =============================================================================
--
-- Conventions (see README.md, "Database migrations"):
--   * This set is a hand-maintained mirror of db/migration (PostgreSQL).
--     Every schema change gets the same version number and shape here.
--   * Keep SQL portable (ANSI). H2 runs in MODE=PostgreSQL, but PostgreSQL-only
--     features (pg_trgm, GIN indexes, native types, functions) have no H2
--     equivalent — such migrations are skipped here with a same-version
--     placeholder file explaining why.
--   * Never edit an applied migration — checksums are validated at startup.
--     Add a new V{n}__*.sql instead.
--
-- Portable design rules used by this migration:
--   * Identifiers are lowercase snake_case (H2 runs with DATABASE_TO_LOWER=TRUE).
--   * Primary keys are UUIDs generated by the application layer, so no
--     database-side default is needed and the DDL is byte-identical on H2 and
--     PostgreSQL. Never rely on gen_random_uuid()/RANDOM_UUID() here.
--   * Enumerations are CHECK constraints on VARCHAR columns (no native enum
--     types, no lookup tables) so both engines can validate them.
--   * Timestamps are TIMESTAMP WITH TIME ZONE (timestamptz) so a single column
--     type works on both engines. Map them to Instant/OffsetDateTime in JPA.
--   * Every table carries created_at/updated_at; updated_at is maintained by
--     the application (@PreUpdate) — no database trigger is portable.
--   * Foreign key names are explicit so Hibernate validation can match them.
--
-- The body below is identical to db/migration/V2__create_core_schema.sql; only
-- this header differs. Keep them in step when editing.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- users — accounts for contributors, moderators and administrators.
-- Anonymous contributions have no user row; they only carry a snapshot of the
-- contributor's display name and contact e-mail on the icon itself.
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    id            UUID                        NOT NULL,
    email         VARCHAR(320)                NOT NULL,
    password_hash VARCHAR(100)                NOT NULL,
    display_name  VARCHAR(120)                NOT NULL,
    role          VARCHAR(20)                 NOT NULL DEFAULT 'CONTRIBUTOR',
    status        VARCHAR(20)                 NOT NULL DEFAULT 'ACTIVE',
    last_login_at TIMESTAMP WITH TIME ZONE,
    created_at    TIMESTAMP WITH TIME ZONE    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('CONTRIBUTOR', 'MODERATOR', 'ADMIN')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'PENDING_VERIFICATION'))
);

CREATE INDEX idx_users_role ON users (role);
CREATE INDEX idx_users_status ON users (status);

-- ---------------------------------------------------------------------------
-- refresh_token — rotating refresh tokens. Only the hash is stored; a token
-- is revoked by stamping revoked_at and is linked to its successor through
-- replaced_by_token_id.
-- ---------------------------------------------------------------------------
CREATE TABLE refresh_token (
    id                  UUID                     NOT NULL,
    user_id             UUID                     NOT NULL,
    token_hash          VARCHAR(128)             NOT NULL,
    issued_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at          TIMESTAMP WITH TIME ZONE,
    replaced_by_token_id UUID,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_refresh_token PRIMARY KEY (id),
    CONSTRAINT uq_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_token_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_refresh_token_replacement FOREIGN KEY (replaced_by_token_id) REFERENCES refresh_token (id) ON DELETE SET NULL
);

CREATE INDEX idx_refresh_token_user ON refresh_token (user_id);
CREATE INDEX idx_refresh_token_expires ON refresh_token (expires_at);

-- ---------------------------------------------------------------------------
-- church — physical place that holds one or more artworks. Duplicates are
-- resolved with merged_into_id instead of being deleted, so history survives.
-- ---------------------------------------------------------------------------
CREATE TABLE church (
    id             UUID                     NOT NULL,
    name           VARCHAR(200)             NOT NULL,
    slug           VARCHAR(220)             NOT NULL,
    region         VARCHAR(120),
    town           VARCHAR(120),
    country        VARCHAR(120)             NOT NULL DEFAULT 'Ethiopia',
    latitude       NUMERIC(9, 6),
    longitude      NUMERIC(9, 6),
    description    TEXT,
    status         VARCHAR(20)              NOT NULL DEFAULT 'ACTIVE',
    merged_into_id UUID,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_church PRIMARY KEY (id),
    CONSTRAINT uq_church_slug UNIQUE (slug),
    CONSTRAINT ck_church_status CHECK (status IN ('ACTIVE', 'MERGED', 'ARCHIVED')),
    CONSTRAINT ck_church_latitude CHECK (latitude IS NULL OR (latitude >= -90 AND latitude <= 90)),
    CONSTRAINT ck_church_longitude CHECK (longitude IS NULL OR (longitude >= -180 AND longitude <= 180)),
    CONSTRAINT ck_church_not_self_merged CHECK (merged_into_id IS NULL OR merged_into_id <> id),
    CONSTRAINT fk_church_merged_into FOREIGN KEY (merged_into_id) REFERENCES church (id) ON DELETE SET NULL
);

CREATE INDEX idx_church_name ON church (name);
CREATE INDEX idx_church_region ON church (region);
CREATE INDEX idx_church_merged_into ON church (merged_into_id);

-- ---------------------------------------------------------------------------
-- church_alias — alternative / historical names of a church. Kept in a child
-- table so searching by an alternative name stays a plain indexed lookup
-- instead of a comma-separated column.
-- ---------------------------------------------------------------------------
CREATE TABLE church_alias (
    id         UUID                     NOT NULL,
    church_id  UUID                     NOT NULL,
    name       VARCHAR(200)             NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_church_alias PRIMARY KEY (id),
    CONSTRAINT uq_church_alias_name UNIQUE (church_id, name),
    CONSTRAINT fk_church_alias_church FOREIGN KEY (church_id) REFERENCES church (id) ON DELETE CASCADE
);

CREATE INDEX idx_church_alias_name ON church_alias (name);

-- ---------------------------------------------------------------------------
-- saint — a depicted figure. Amharic and Ge'ez names are first-class columns
-- because they are functionally dependent on the saint (1:1), while further
-- alternative spellings live in saint_alias.
-- ---------------------------------------------------------------------------
CREATE TABLE saint (
    id             UUID                     NOT NULL,
    canonical_name VARCHAR(200)             NOT NULL,
    slug           VARCHAR(220)             NOT NULL,
    amharic_name   VARCHAR(200),
    geez_name      VARCHAR(200),
    category       VARCHAR(80),
    description    TEXT,
    is_verified    BOOLEAN                  NOT NULL DEFAULT FALSE,
    status         VARCHAR(20)              NOT NULL DEFAULT 'ACTIVE',
    merged_into_id UUID,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_saint PRIMARY KEY (id),
    CONSTRAINT uq_saint_slug UNIQUE (slug),
    CONSTRAINT ck_saint_status CHECK (status IN ('ACTIVE', 'MERGED', 'ARCHIVED')),
    CONSTRAINT ck_saint_not_self_merged CHECK (merged_into_id IS NULL OR merged_into_id <> id),
    CONSTRAINT fk_saint_merged_into FOREIGN KEY (merged_into_id) REFERENCES saint (id) ON DELETE SET NULL
);

CREATE INDEX idx_saint_canonical_name ON saint (canonical_name);
CREATE INDEX idx_saint_category ON saint (category);
CREATE INDEX idx_saint_merged_into ON saint (merged_into_id);

-- ---------------------------------------------------------------------------
-- saint_alias — alternative spellings / transliterations of a saint's name.
-- ---------------------------------------------------------------------------
CREATE TABLE saint_alias (
    id         UUID                     NOT NULL,
    saint_id   UUID                     NOT NULL,
    name       VARCHAR(200)             NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_saint_alias PRIMARY KEY (id),
    CONSTRAINT uq_saint_alias_name UNIQUE (saint_id, name),
    CONSTRAINT fk_saint_alias_saint FOREIGN KEY (saint_id) REFERENCES saint (id) ON DELETE CASCADE
);

CREATE INDEX idx_saint_alias_name ON saint_alias (name);

-- ---------------------------------------------------------------------------
-- icon — the artwork record and the root of the aggregate.
--
--   publication_status : PENDING -> APPROVED | REJECTED | NEEDS_CORRECTION,
--                         plus ARCHIVED for withdrawn records. Approving sets
--                         published_at.
--   figure_certainty   : roll-up of the primary subject's identification
--                         certainty (see icon_subject.figure_certainty).
--   contributor_*      : snapshot of who submitted the icon. The display name
--                         is stored on purpose (an anonymous submission has no
--                         user row, and a user may later change their name).
--   contact_email      : PRIVATE. Never expose it in a public DTO.
--   capture_date       : date the icon was photographed; mirrors the date part
--                         of the primary icon_image.captured_at.
-- ---------------------------------------------------------------------------
CREATE TABLE icon (
    id                       UUID                     NOT NULL,
    title                    VARCHAR(240)             NOT NULL,
    slug                     VARCHAR(260)             NOT NULL,
    reference_code           VARCHAR(32)              NOT NULL,
    church_id                UUID,
    figure_certainty         VARCHAR(20)              NOT NULL DEFAULT 'UNKNOWN',
    description              TEXT,
    historical_notes         TEXT,
    category                 VARCHAR(80),
    capture_date             DATE,
    artwork_date_start       DATE,
    artwork_date_end         DATE,
    contributor_user_id      UUID,
    contributor_display_name VARCHAR(120),
    attribution_preference   VARCHAR(20)              NOT NULL DEFAULT 'DISPLAY_NAME',
    contact_email            VARCHAR(320),
    publication_status       VARCHAR(20)              NOT NULL DEFAULT 'PENDING',
    moderation_notes         TEXT,
    published_at             TIMESTAMP WITH TIME ZONE,
    created_at               TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at               TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_icon PRIMARY KEY (id),
    CONSTRAINT uq_icon_slug UNIQUE (slug),
    CONSTRAINT uq_icon_reference_code UNIQUE (reference_code),
    CONSTRAINT ck_icon_figure_certainty CHECK (figure_certainty IN ('IDENTIFIED', 'PROBABLE', 'UNKNOWN')),
    CONSTRAINT ck_icon_attribution_preference CHECK (attribution_preference IN ('DISPLAY_NAME', 'ANONYMOUS')),
    CONSTRAINT ck_icon_publication_status CHECK (publication_status IN ('PENDING', 'APPROVED', 'REJECTED', 'NEEDS_CORRECTION', 'ARCHIVED')),
    CONSTRAINT ck_icon_artwork_date_range CHECK (artwork_date_start IS NULL OR artwork_date_end IS NULL OR artwork_date_end >= artwork_date_start),
    CONSTRAINT ck_icon_approved_has_published_at CHECK (publication_status <> 'APPROVED' OR published_at IS NOT NULL),
    CONSTRAINT fk_icon_church FOREIGN KEY (church_id) REFERENCES church (id) ON DELETE SET NULL,
    CONSTRAINT fk_icon_contributor FOREIGN KEY (contributor_user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_icon_status_created ON icon (publication_status, created_at DESC);
CREATE INDEX idx_icon_church ON icon (church_id);
CREATE INDEX idx_icon_category ON icon (category);
CREATE INDEX idx_icon_contributor ON icon (contributor_user_id);

-- ---------------------------------------------------------------------------
-- icon_subject — the figures depicted on an icon (many-to-many with saint).
--
-- An icon may depict an unknown / unidentified figure: in that case saint_id
-- is NULL and figure_certainty is 'UNKNOWN', while subject_label keeps the
-- caption that appears on the artwork. Because saint_id is nullable it cannot
-- be part of a composite primary key, so the table uses a surrogate UUID key
-- plus a uniqueness rule on (icon_id, subject_label).
--
-- The FK to saint uses ON DELETE RESTRICT on purpose: saints are merged
-- (merged_into_id), never deleted, and a cascading SET NULL would violate
-- ck_icon_subject_identified for identified rows.
-- ---------------------------------------------------------------------------
CREATE TABLE icon_subject (
    id               UUID                     NOT NULL,
    icon_id          UUID                     NOT NULL,
    saint_id         UUID,
    subject_label    VARCHAR(200)             NOT NULL,
    figure_certainty VARCHAR(20)              NOT NULL DEFAULT 'UNKNOWN',
    is_primary       BOOLEAN                  NOT NULL DEFAULT FALSE,
    sort_order       INTEGER                  NOT NULL DEFAULT 0,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_icon_subject PRIMARY KEY (id),
    CONSTRAINT uq_icon_subject_label UNIQUE (icon_id, subject_label),
    CONSTRAINT ck_icon_subject_certainty CHECK (figure_certainty IN ('IDENTIFIED', 'PROBABLE', 'UNKNOWN')),
    CONSTRAINT ck_icon_subject_identified CHECK (saint_id IS NOT NULL OR figure_certainty = 'UNKNOWN'),
    CONSTRAINT fk_icon_subject_icon FOREIGN KEY (icon_id) REFERENCES icon (id) ON DELETE CASCADE,
    CONSTRAINT fk_icon_subject_saint FOREIGN KEY (saint_id) REFERENCES saint (id) ON DELETE RESTRICT
);

CREATE INDEX idx_icon_subject_icon ON icon_subject (icon_id);
CREATE INDEX idx_icon_subject_saint ON icon_subject (saint_id);

-- ---------------------------------------------------------------------------
-- icon_image — the photographs of an icon. One icon has many images; exactly
-- one of them is expected to be the primary (is_primary) image.
-- storage_key points into the media store (local filesystem or S3/MinIO).
-- ---------------------------------------------------------------------------
CREATE TABLE icon_image (
    id                    UUID                     NOT NULL,
    icon_id               UUID                     NOT NULL,
    storage_key           VARCHAR(500)             NOT NULL,
    thumbnail_storage_key VARCHAR(500),
    content_type          VARCHAR(120)             NOT NULL,
    file_size_bytes       BIGINT                   NOT NULL,
    checksum_sha256       VARCHAR(64)              NOT NULL,
    width_px              INTEGER,
    height_px             INTEGER,
    alt_text              VARCHAR(500),
    is_primary            BOOLEAN                  NOT NULL DEFAULT FALSE,
    sort_order            INTEGER                  NOT NULL DEFAULT 0,
    captured_at           TIMESTAMP WITH TIME ZONE,
    uploaded_by           UUID,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_icon_image PRIMARY KEY (id),
    CONSTRAINT uq_icon_image_storage_key UNIQUE (storage_key),
    CONSTRAINT uq_icon_image_checksum UNIQUE (icon_id, checksum_sha256),
    CONSTRAINT ck_icon_image_file_size CHECK (file_size_bytes > 0),
    CONSTRAINT ck_icon_image_checksum_length CHECK (LENGTH(checksum_sha256) = 64),
    CONSTRAINT ck_icon_image_width CHECK (width_px IS NULL OR width_px > 0),
    CONSTRAINT ck_icon_image_height CHECK (height_px IS NULL OR height_px > 0),
    CONSTRAINT fk_icon_image_icon FOREIGN KEY (icon_id) REFERENCES icon (id) ON DELETE CASCADE,
    CONSTRAINT fk_icon_image_uploader FOREIGN KEY (uploaded_by) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_icon_image_icon ON icon_image (icon_id, sort_order);

-- ---------------------------------------------------------------------------
-- image_rights — the rights and attribution statement of a single image.
-- One row per image (uq_image_rights_image). The licence of the artwork and
-- the licence of the photograph are distinct records, so the statement that
-- is legally binding for the image is stored next to the image itself.
-- ---------------------------------------------------------------------------
CREATE TABLE image_rights (
    id               UUID                     NOT NULL,
    icon_image_id    UUID                     NOT NULL,
    rights_holder    VARCHAR(200),
    license_type     VARCHAR(40)              NOT NULL DEFAULT 'UNKNOWN',
    license_url      VARCHAR(500),
    license_notes    TEXT,
    attribution_text VARCHAR(500),
    copyright_year   INTEGER,
    is_verified      BOOLEAN                  NOT NULL DEFAULT FALSE,
    verified_by      UUID,
    verified_at      TIMESTAMP WITH TIME ZONE,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_image_rights PRIMARY KEY (id),
    CONSTRAINT uq_image_rights_image UNIQUE (icon_image_id),
    CONSTRAINT ck_image_rights_license CHECK (license_type IN ('PUBLIC_DOMAIN', 'CC_BY', 'CC_BY_SA', 'CC_BY_NC', 'CC_BY_NC_ND', 'ALL_RIGHTS_RESERVED', 'PERMISSION_GRANTED', 'UNKNOWN')),
    CONSTRAINT ck_image_rights_copyright_year CHECK (copyright_year IS NULL OR (copyright_year >= 1000 AND copyright_year <= 3000)),
    CONSTRAINT fk_image_rights_image FOREIGN KEY (icon_image_id) REFERENCES icon_image (id) ON DELETE CASCADE,
    CONSTRAINT fk_image_rights_verifier FOREIGN KEY (verified_by) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_image_rights_license ON image_rights (license_type);

-- ---------------------------------------------------------------------------
-- contribution_review — immutable moderation trail for a contribution.
-- Rows are only ever inserted; from_status/to_status record the state
-- transition that the review caused.
-- ---------------------------------------------------------------------------
CREATE TABLE contribution_review (
    id          UUID                     NOT NULL,
    icon_id     UUID                     NOT NULL,
    reviewer_id UUID                     NOT NULL,
    action      VARCHAR(30)              NOT NULL,
    from_status VARCHAR(20),
    to_status   VARCHAR(20),
    notes       TEXT,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_contribution_review PRIMARY KEY (id),
    CONSTRAINT ck_contribution_review_action CHECK (action IN ('SUBMIT', 'APPROVE', 'REJECT', 'REQUEST_CORRECTION', 'COMMENT', 'WITHDRAW')),
    CONSTRAINT ck_contribution_review_from_status CHECK (from_status IS NULL OR from_status IN ('PENDING', 'APPROVED', 'REJECTED', 'NEEDS_CORRECTION', 'ARCHIVED')),
    CONSTRAINT ck_contribution_review_to_status CHECK (to_status IS NULL OR to_status IN ('PENDING', 'APPROVED', 'REJECTED', 'NEEDS_CORRECTION', 'ARCHIVED')),
    CONSTRAINT fk_contribution_review_icon FOREIGN KEY (icon_id) REFERENCES icon (id) ON DELETE CASCADE,
    CONSTRAINT fk_contribution_review_reviewer FOREIGN KEY (reviewer_id) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX idx_contribution_review_icon ON contribution_review (icon_id, created_at DESC);
CREATE INDEX idx_contribution_review_reviewer ON contribution_review (reviewer_id);

-- ---------------------------------------------------------------------------
-- audit_log — administrative action log. Written for every privileged
-- operation; actor_user_id is nullable so the trail survives account removal.
-- detail holds a JSON document as TEXT (JSONB is PostgreSQL-only).
-- ---------------------------------------------------------------------------
CREATE TABLE audit_log (
    id            UUID                     NOT NULL,
    actor_user_id UUID,
    action        VARCHAR(80)              NOT NULL,
    entity_type   VARCHAR(60)              NOT NULL,
    entity_id     UUID,
    detail        TEXT,
    ip_address    VARCHAR(45),
    user_agent    VARCHAR(300),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_audit_log PRIMARY KEY (id),
    CONSTRAINT fk_audit_log_actor FOREIGN KEY (actor_user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_audit_log_entity ON audit_log (entity_type, entity_id);
CREATE INDEX idx_audit_log_actor ON audit_log (actor_user_id);
CREATE INDEX idx_audit_log_created ON audit_log (created_at DESC);
